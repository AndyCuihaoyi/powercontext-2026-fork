CREATE DATABASE IF NOT EXISTS pawnshop DEFAULT CHARACTER SET utf8mb4;
USE pawnshop;

CREATE TABLE IF NOT EXISTS players (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(64) NOT NULL UNIQUE,
  scope_id VARCHAR(64) NOT NULL DEFAULT '',
  scope_key VARCHAR(128) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tickets (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  ticket_no VARCHAR(32) NOT NULL UNIQUE,
  player_id BIGINT NOT NULL,
  memory TEXT NOT NULL,
  appraisal MEDIUMTEXT NOT NULL,
  value INT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT 'pawned',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_player (player_id),
  FULLTEXT KEY ft_ticket (memory, appraisal) WITH PARSER ik
);
